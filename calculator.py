
num1 = float(input("Insert a number: "))
op = str(input("Insert a operator: "))
num2 = float(input("Insert a operator: "))

if op == '*' :
    result = num1 * num2

if op == '/' :
    result = num1 / num2

if op == '+' :
    result = num1 + num2

if op == '-':
    result = num1 - num2

print(result)